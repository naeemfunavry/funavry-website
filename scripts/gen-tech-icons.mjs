/**
 * Codegen: emits src/lib/tech-icons.ts with only the brand marks we render.
 *
 * Importing `simple-icons` directly would pull ~3,400 icons into the client
 * bundle. Run this whenever the TechStack list changes:
 *
 *   node scripts/gen-tech-icons.mjs
 *
 * Names that Simple Icons does not carry are reported and simply omitted —
 * <TechIcon> renders a monogram for those. Simple Icons removes marks on
 * trademark-holder request (Amazon, Microsoft, OpenAI), and many smaller
 * vendors were never submitted.
 */
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

/** Our display name -> the official Simple Icons `title`.
 *
 * The list mirrors the Technology Stack section of the company profile. Where a
 * product has no mark of its own but is a service of a vendor that does, the
 * vendor's mark stands in — GKE and Vertex AI take Google Cloud's, ARKit takes
 * Apple's — which is the mark those products actually ship under.
 */
